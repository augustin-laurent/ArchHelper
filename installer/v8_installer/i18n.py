def resolve_code():
    """V8_LANG, then the omarchy language file, validated; French as the floor."""
    code = os.environ.get("V8_LANG", "")
    if not code:
        for candidate in (os.environ.get("XDG_CONFIG_HOME"), str(Path.home() / ".config")):
            if not candidate:
                continue
            try:
                code = (Path(candidate) / "omarchy" / "language").read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            break
    code = (code or "").strip().splitlines()[0].strip() if (code or "").strip() else ""
    # Purposeful whitelist: the installer only ever ships two catalogs, and a
    # malformed file must not leak a half-language into a disk-writing tool.
    return code if re.fullmatch(r"[a-z]{2,3}(-[A-Za-z]{2})?", code) else "fr"


def current():
    """Resolved once per process: exact catalog, else base, else French."""
    global _current
    if _current is None:
        code = resolve_code()
        _current = code if code in _CATALOGS else (code.split("-")[0] if code.split("-")[0] in _CATALOGS else "fr")
    return _current


def t(key):
    catalog = _CATALOGS[current()]
    value = catalog.get(key)
    if value is None:
        # A missing key in the language's own catalog reads in English rather
        # than crashing; a missing key anywhere reads as its key name.
        value = _EN.get(key, key)
    return value
